"""Reproduce wave-maturity subset CSVs from the previously calculated trade-level feature CSV.
Input DD_causal_wave_maturity_trades.csv is generated by dd_causal_wave_maturity.py
from DD_structure_trade_detail.csv and EURUSD2003_M15.pkl.
This is a RETROSPECTIVE FILTER of original EA trades, not a new EA backtest.
Usage: python research/ea_shared/reproduce_wave_subset_20261015.py --input /path/to/DD_causal_wave_maturity_trades.csv --out /path/to/output
"""
import argparse
from pathlib import Path
import numpy as np
import pandas as pd

def summarize(df, label):
    x=df.sort_values(["exit_time","time"],kind="stable")
    r=x["R"].to_numpy(dtype=float)
    eq=np.r_[0.,np.cumsum(r)]
    dd=eq-np.maximum.accumulate(eq)
    trough=int(np.argmin(dd))
    peak=int(np.argmax(eq[:trough+1]))
    gains=r[r>0]; losses=r[r<0]
    longest=max(map(len,"".join("L" if v<0 else "W" for v in r).split("W")))
    return dict(condition=label,n=len(r),wins=len(gains),losses=len(losses),
      breakeven=int((r==0).sum()),winrate=len(gains)/len(r),
      sumR=float(r.sum()),PF=float(gains.sum()/-losses.sum()),
      avgR=float(r.mean()),avgWinR=float(gains.mean()),avgLossR=float(losses.mean()),
      maxDD_closed_R=float(dd.min()),
      peak_date=str(x.iloc[peak-1].exit_time) if peak else "initial",
      trough_date=str(x.iloc[trough-1].exit_time) if trough else "initial",
      max_winR=float(r.max()),max_lossR=float(r.min()),
      longest_loss_streak=longest,yearly_avg_count=len(r)/24)

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--input",required=True)
    ap.add_argument("--out",required=True)
    a=ap.parse_args()
    out=Path(a.out);out.mkdir(parents=True,exist_ok=True)
    d=pd.read_csv(a.input,parse_dates=["time","exit_time"])
    base=(d.h4_impulse_ratio>=0.70)&(d.h1_impulse_ratio<0.75)
    rows=[]
    for label,mask,suffix in [
      ("H4 maintained + H1 contracted (359)",base,"359"),
      ("Above + SMA480 distance <12 ATR (284)",base&(d.d480<12),"284")]:
        x=d.loc[mask].copy()
        rows.append(summarize(x,label))
        x.sort_values(["exit_time","time"],kind="stable").to_csv(out/f"DD_wave_trades_{suffix}.csv",index=False)
        yearly=x.groupby(x.time.dt.year).R.agg(trades="size",sumR="sum")
        yearly.index.name="time"
        yearly.to_csv(out/f"DD_wave_annual_{suffix}.csv")
    pd.DataFrame(rows).to_csv(out/"DD_wave_subset_performance_20261015.csv",index=False)
    print(pd.DataFrame(rows).to_string(index=False))
if __name__=="__main__":main()
